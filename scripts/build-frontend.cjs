'use strict';

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {checkpointTrial} = require('./checkpoint-trial.cjs');

const MANIFEST = 'scripts/frontend-manifest.json';

function relativeFile(name) {
  if (typeof name !== 'string' || !/^[\w./-]+$/.test(name) || path.posix.isAbsolute(name) || name.split('/').some(part => !part || part === '.' || part === '..')) {
    throw new Error('Frontend paths must be plain project-relative files: ' + name);
  }
  return name;
}

function assertPlainTree(filename) {
  const stat = fs.lstatSync(filename);
  if (stat.isSymbolicLink()) throw new Error('Frontend files must not contain links: ' + filename);
  if (stat.isDirectory()) for (const entry of fs.readdirSync(filename)) assertPlainTree(path.join(filename, entry));
}

function readInput(root, name) {
  relativeFile(name);
  let filename = root;
  for (const part of name.split('/')) {
    filename = path.join(filename, part);
    if (fs.lstatSync(filename).isSymbolicLink()) throw new Error('Frontend inputs must not contain links: ' + name);
  }
  if (!fs.statSync(filename).isFile() || fs.realpathSync(filename) !== filename) throw new Error('Frontend input must be a plain project file: ' + name);
  return fs.readFileSync(filename);
}

function readManifest(root) {
  const manifest = JSON.parse(readInput(root, MANIFEST).toString('utf8'));
  if (manifest.bundle !== 'app.bundle.js' || !Array.isArray(manifest.scripts) || !Array.isArray(manifest.assets) || !Array.isArray(manifest.copies)) throw new Error('Invalid frontend manifest');
  if (!manifest.scripts.length || manifest.scripts.at(-1) !== 'app.js') throw new Error('app.js must be the final startup entry');
  if (Object.keys(manifest).some(key => !['bundle', 'scripts', 'assets', 'copies'].includes(key))) throw new Error('Unknown frontend manifest field');
  const sources = new Set(), outputs = new Set([manifest.bundle.toLowerCase()]);
  for (const source of manifest.scripts) {
    relativeFile(source);
    if (!source.endsWith('.js') || sources.has(source.toLowerCase())) throw new Error('Duplicate or invalid frontend script: ' + source);
    sources.add(source.toLowerCase());
  }
  for (const copy of manifest.copies) {
    if (!copy || Object.keys(copy).sort().join(',') !== 'destination,source') throw new Error('Invalid frontend copy');
  }
  for (const [source, destination] of [...manifest.assets.map(asset => [asset, asset]), ...manifest.copies.map(copy => [copy.source, copy.destination])]) {
    relativeFile(source); relativeFile(destination);
    if (source.toLowerCase().endsWith('.js') || destination.toLowerCase().endsWith('.js') || outputs.has(destination.toLowerCase())) throw new Error('Duplicate or invalid frontend output: ' + destination);
    outputs.add(destination.toLowerCase());
  }
  if (!manifest.assets.includes('index.html')) throw new Error('The frontend manifest must include index.html');
  return manifest;
}

function buildFrontend(options = {}) {
  const root = fs.realpathSync(options.root || path.join(__dirname, '..'));
  const manifest = readManifest(root), files = new Map(), inputs = new Set([MANIFEST, 'scripts/build-frontend.cjs', 'scripts/checkpoint-trial.cjs', 'scripts/check-storage.cjs', 'scripts/storage-policy.json']);
  const chunks = ['/* Generated by scripts/build-frontend.cjs. Edit the module sources, not this file. */\n'];
  for (const name of manifest.scripts) {
    const source = readInput(root, name).toString('utf8');
    new vm.Script(source, { filename: name });
    chunks.push('\n;/* ' + name + ' */\n' + source + '\n');
    inputs.add(name);
  }
  const bundle = chunks.join('');
  // Keep classic-script semantics: no CommonJS wrappers, import rewriting or global renaming.
  new vm.Script(bundle, { filename: manifest.bundle });
  files.set(manifest.bundle, Buffer.from(bundle));
  for (const [source, destination] of [...manifest.assets.map(asset => [asset, asset]), ...manifest.copies.map(copy => [copy.source, copy.destination])]) {
    files.set(destination, readInput(root, source));
    inputs.add(source);
  }
  const html = files.get('index.html').toString('utf8'), scripts = [...html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script\s*>/gi)];
  if (scripts.length !== 1 || !/(?:^|\s)src\s*=\s*["']app\.bundle\.js["']/i.test(scripts[0][1]) || scripts[0][2].trim()) throw new Error('index.html must load only app.bundle.js');
  for (const [, asset] of html.matchAll(/(?:src|href)=["']([^"'#]+\.(?:js|css))["']/g)) {
    if (!files.has(asset)) throw new Error('Unpackaged frontend asset: ' + asset);
  }
  // Validate every input before replacing the generated directory. Never follow an old dist link.
  const dist = path.join(root, 'dist');
  checkpointTrial(root);
  let previous;
  try { previous = fs.lstatSync(dist); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previous) {
    assertPlainTree(dist);
    if (!fs.statSync(dist).isDirectory() || fs.realpathSync(dist) !== dist) throw new Error('Generated dist must be a plain project directory');
    fs.rmSync(dist, { recursive: true });
  }
  for (const [name, data] of files) {
    const output = path.join(dist, ...name.split('/'));
    fs.mkdirSync(path.dirname(output), { recursive: true });
    fs.writeFileSync(output, data);
  }
  if (options.cargo) for (const input of inputs) process.stdout.write('cargo:rerun-if-changed=' + path.join(root, input) + '\n');
  return { dist, files: [...files.keys()].sort(), scripts: manifest.scripts.slice(), bytes: Buffer.byteLength(bundle) };
}

if (require.main === module) {
  try {
    if (process.argv.slice(2).some(argument => argument !== '--cargo')) throw new Error('Usage: node scripts/build-frontend.cjs [--cargo]');
    const result = buildFrontend({ cargo: process.argv.includes('--cargo') });
    if (!process.argv.includes('--cargo')) process.stdout.write('Built ' + result.files.length + ' frontend assets; 1 JavaScript bundle (' + result.bytes + ' bytes).\n');
  } catch (error) {
    process.stderr.write('Frontend build failed: ' + error.message + '\n');
    process.exitCode = 1;
  }
}

module.exports = { buildFrontend, readManifest, assertPlainTree };
